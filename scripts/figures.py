#!/usr/bin/env python3
"""Write or check the dark twin of every figure.

Each light SVG uses only the colors in TOKENS. Its dark twin is the same file
with every light value swapped for its dark value, so the two cannot drift.

  python3 scripts/figures.py --write   regenerate every dark twin
  python3 scripts/figures.py --check   exit 1 and name the file when a twin is
                                       missing, stale or without a light file,
                                       or a light file uses a color outside
                                       TOKENS

Colors are read only where SVG takes one: the fill, stroke, stop-color,
flood-color and color attributes, and the same properties inside style
attributes and <style> blocks. A value there must be a TOKENS color or one of
KEYWORDS; text such as a label reading "#263" is not a color.

The social preview has no twin; after changing its SVG, render the PNG with
  rsvg-convert -w 1280 -h 640 docs/assets/readme/social-preview.svg -o docs/assets/readme/social-preview.png
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Light value -> dark value. Dark values follow GitHub's dark theme (#0D1117 page).
TOKENS = {
    "#FFFFFF": "#0D1117",  # paper: background
    "#111827": "#E6EDF3",  # ink: text
    "#CBD5E1": "#30363D",  # line: rules, gridlines, timeline
    "#475569": "#9198A1",  # muted: labels, arrows, axes
    "#94A3B8": "#6E7681",  # neutral: outline of a neutral box, the baseline bar
    "#F1F5F9": "#161B22",  # panel: fill of a neutral box, terminal title bar
    "#6D28D9": "#A78BFA",  # planner: the strong model's steps
    "#EDE9FE": "#2E1F5E",  # planner tint
    "#B45309": "#F0B429",  # you (amber): the owner's decisions and gates
    "#FEF3C7": "#3D2E00",  # you tint
    "#1D4ED8": "#60A5FA",  # judge (blue): the plan verifier and the reviewers
    "#DBEAFE": "#172554",  # judge tint
    "#0F766E": "#2DD4BF",  # check: cheap model, grading, PASS
    "#CCFBF1": "#0B3D38",  # check tint
    "#5EEAD4": "#1A9C8C",  # check middle: the middle bar of a teal scale
    "#B91C1C": "#F87171",  # stop: failures and refusals
    "#FEE2E2": "#3F1519",  # stop tint
}

# Light files with a dark twin beside them: <name>.svg -> <name>-dark.svg, <name>-light.svg -> <name>-dark.svg.
# The figures and the demo card draw a rounded paper rect, so each twin reads as a dark card on any page;
# the wordmark draws none and stays transparent.
LIGHT = sorted(p for p in (ROOT / "docs/figures").glob("*.svg") if not p.stem.endswith("-dark")) + [
    ROOT / "assets/concord-wordmark.svg",
    ROOT / "docs/assets/readme/demo-light.svg",
]
# Light files without a twin; their colors are checked all the same.
LIGHT_ONLY = [ROOT / "docs/assets/readme/social-preview.svg"]

# Values allowed at a color position besides the TOKENS colors: only what the figures use.
KEYWORDS = {"none"}

COLOR = r"(?:fill|stroke|stop-color|flood-color|color)"
TAG = re.compile(r"<[A-Za-z][^>]*>")  # start tags only: comments and text are skipped
ATTR = re.compile(r"(\s" + COLOR + r"\s*=\s*([\"']))(.*?)(\2)", re.S)
STYLE_ATTR = re.compile(r"(\sstyle\s*=\s*([\"']))(.*?)(\2)", re.S)
STYLE_BLOCK = re.compile(r"(<style\b[^>]*>)(.*?)(</style>)", re.S)
PROP = re.compile(r"((?<![\w-])" + COLOR + r"\s*:\s*)([^;}]*[^;}\s])")


def twin_of(light):
    stem = light.stem[: -len("-light")] if light.stem.endswith("-light") else light.stem
    return light.with_name(stem + "-dark.svg")


def map_colors(text, fn):
    """Return text with fn applied to the value at every color position."""
    css = lambda body: PROP.sub(lambda m: m.group(1) + fn(m.group(2)), body)
    def tag(m):
        t = ATTR.sub(lambda a: a.group(1) + fn(a.group(3)) + a.group(4), m.group())
        return STYLE_ATTR.sub(lambda a: a.group(1) + css(a.group(3)) + a.group(4), t)
    text = STYLE_BLOCK.sub(lambda m: m.group(1) + css(m.group(2)) + m.group(3), text)
    return TAG.sub(tag, text)


def strays(text):
    seen = set()
    map_colors(text, lambda v: seen.add(v) or v)
    return sorted(v for v in seen if v.upper() not in TOKENS and v not in KEYWORDS)


def dark(text, name):
    body = map_colors(text, lambda v: TOKENS.get(v.upper(), v))
    at = body.index(">", body.index("<svg")) + 1
    note = f"\n  <!-- Generated by scripts/figures.py from {name}. Edit that file and regenerate this one. -->"
    return body[:at] + note + body[at:]


def main(argv):
    if argv not in (["--write"], ["--check"]):
        print(__doc__.strip(), file=sys.stderr)
        return 2
    write = argv == ["--write"]
    problems = []
    for light in LIGHT + LIGHT_ONLY:
        rel = light.relative_to(ROOT)
        if not light.exists():
            problems.append(f"{rel}: missing")
            continue
        text = light.read_text(encoding="utf-8")
        if strays(text):
            problems.append(f"{rel}: colors outside the token table: {' '.join(strays(text))}")
            continue
        if light in LIGHT_ONLY:
            continue
        twin, want = twin_of(light), dark(text, light.name)
        have = twin.read_text(encoding="utf-8") if twin.exists() else None
        if have == want:
            continue
        if write:
            twin.write_text(want, encoding="utf-8")
            print(f"wrote {twin.relative_to(ROOT)}")
        else:
            state = "missing" if have is None else f"differs from what --write makes of {light.name}"
            problems.append(f"{twin.relative_to(ROOT)}: {state}")
    twins = {twin_of(p) for p in LIGHT}
    folders = sorted({p.parent for p in LIGHT + LIGHT_ONLY})
    for p in sorted(q for folder in folders for q in folder.glob("*-dark.svg")):
        if p not in twins:
            problems.append(f"{p.relative_to(ROOT)}: no light file")
    for line in problems:
        print(f"figures: {line}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
